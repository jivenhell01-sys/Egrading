/**
 * Helper functions for Samar barangays data
 * Provides convenient ways to access and search barangay information
 */

/**
 * Get all municipalities/cities of Samar
 * @return array List of all municipalities and cities
 */
function get_samar_municipalities() {
    global $samar_barangays;
    return array_keys($samar_barangays);
}

/**
 * Get all barangays for a specific municipality
 * @param string $municipality Name of municipality
 * @return array List of barangays or empty array if not found
 */
function get_samar_barangays_by_municipality($municipality) {
    global $samar_barangays;
    return isset($samar_barangays[$municipality]) ? $samar_barangays[$municipality] : array();
}

/**
 * Get all barangays of Samar (flattened array)
 * @return array All barangays across all municipalities
 */
function get_all_samar_barangays() {
    global $samar_barangays;
    $all_barangays = array();
    foreach ($samar_barangays as $municipality => $barangays) {
        $all_barangays = array_merge($all_barangays, $barangays);
    }
    return $all_barangays;
}

/**
 * Count barangays in a municipality
 * @param string $municipality Name of municipality
 * @return int Number of barangays
 */
function count_samar_barangays($municipality) {
    global $samar_barangays;
    return isset($samar_barangays[$municipality]) ? count($samar_barangays[$municipality]) : 0;
}

/**
 * Get total number of barangays in Samar
 * @return int Total barangays count
 */
function get_total_samar_barangays() {
    global $samar_barangays;
    $total = 0;
    foreach ($samar_barangays as $barangays) {
        $total += count($barangays);
    }
    return $total;
}

/**
 * Search for a barangay by name
 * @param string $search_term Barangay name to search
 * @return array Array of municipalities where barangay was found
 */
function search_samar_barangay($search_term) {
    global $samar_barangays;
    $results = array();
    
    foreach ($samar_barangays as $municipality => $barangays) {
        if (in_array($search_term, $barangays)) {
            $results[] = $municipality;
        }
    }
    
    return $results;
}

/**
 * Get complete Samar barangays data
 * @return array Complete data structure
 */
function get_samar_barangays_data() {
    global $samar_barangays;
    return $samar_barangays;
}

