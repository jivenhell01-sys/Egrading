/**
 * Helper functions for Leyte barangays data
 * Provides convenient ways to access and search barangay information
 */

/**
 * Get all municipalities/cities of Leyte
 * @return array List of all municipalities and cities
 */
function get_leyte_municipalities() {
    global $leyte_barangays;
    return array_keys($leyte_barangays);
}

/**
 * Get all barangays for a specific municipality
 * @param string $municipality Name of municipality
 * @return array List of barangays or empty array if not found
 */
function get_leyte_barangays_by_municipality($municipality) {
    global $leyte_barangays;
    return isset($leyte_barangays[$municipality]) ? $leyte_barangays[$municipality] : array();
}

/**
 * Get all barangays of Leyte (flattened array)
 * @return array All barangays across all municipalities
 */
function get_all_leyte_barangays() {
    global $leyte_barangays;
    $all_barangays = array();
    foreach ($leyte_barangays as $municipality => $barangays) {
        $all_barangays = array_merge($all_barangays, $barangays);
    }
    return $all_barangays;
}

/**
 * Count barangays in a municipality
 * @param string $municipality Name of municipality
 * @return int Number of barangays
 */
function count_leyte_barangays($municipality) {
    global $leyte_barangays;
    return isset($leyte_barangays[$municipality]) ? count($leyte_barangays[$municipality]) : 0;
}

/**
 * Get total number of barangays in Leyte
 * @return int Total barangays count
 */
function get_total_leyte_barangays() {
    global $leyte_barangays;
    $total = 0;
    foreach ($leyte_barangays as $barangays) {
        $total += count($barangays);
    }
    return $total;
}

/**
 * Search for a barangay by name
 * @param string $search_term Barangay name to search
 * @return array Array of municipalities where barangay was found
 */
function search_leyte_barangay($search_term) {
    global $leyte_barangays;
    $results = array();
    
    foreach ($leyte_barangays as $municipality => $barangays) {
        if (in_array($search_term, $barangays)) {
            $results[] = $municipality;
        }
    }
    
    return $results;
}

/**
 * Get complete Leyte barangays data
 * @return array Complete data structure
 */
function get_leyte_barangays_data() {
    global $leyte_barangays;
    return $leyte_barangays;
}

