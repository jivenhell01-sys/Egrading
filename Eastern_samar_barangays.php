/**
 * Function to get all municipalities of Eastern Samar
 * @return array List of all municipalities
 */
function getEasternSamarMunicipalities() {
    global $eastern_samar_barangays;
    return array_keys($eastern_samar_barangays);
}

/**
 * Function to get barangays of a specific municipality
 * @param string $municipality Name of the municipality
 * @return array List of barangays in the municipality
 */
function getBarangaysByMunicipality($municipality) {
    global $eastern_samar_barangays;
    return isset($eastern_samar_barangays[$municipality]) 
        ? $eastern_samar_barangays[$municipality] 
        : [];
}

/**
 * Function to get all municipalities and their barangays
 * @return array Complete list of municipalities and their barangays
 */
function getAllEasternSamarBarangays() {
    global $eastern_samar_barangays;
    return $eastern_samar_barangays;
}

/**
 * Function to count total barangays in Eastern Samar
 * @return int Total number of barangays
 */
function countTotalBarangays() {
    global $eastern_samar_barangays;
    $total = 0;
    foreach ($eastern_samar_barangays as $barangays) {
        $total += count($barangays);
    }
    return $total;
}

/**
 * Function to search for a specific barangay across all municipalities
 * @param string $barangayName Name of the barangay to search
 * @return array List of municipalities where the barangay is found
 */
function searchBarangay($barangayName) {
    global $eastern_samar_barangays;
    $results = [];
    
    foreach ($eastern_samar_barangays as $municipality => $barangays) {
        if (in_array($barangayName, $barangays)) {
            $results[] = $municipality;
        }
    }
    
    return $results;
}

