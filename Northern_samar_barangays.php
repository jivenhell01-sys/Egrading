/**
 * Function to get all municipalities of Northern Samar
 * @return array List of all municipalities
 */
function getNorthernSamarMunicipalities() {
    global $northern_samar_barangays;
    return array_keys($northern_samar_barangays);
}

/**
 * Function to get barangays of a specific municipality
 * @param string $municipality Name of the municipality
 * @return array List of barangays in the municipality
 */
function getNorthernSamarBarangaysByMunicipality($municipality) {
    global $northern_samar_barangays;
    return isset($northern_samar_barangays[$municipality]) 
        ? $northern_samar_barangays[$municipality] 
        : [];
}

/**
 * Function to get all municipalities and their barangays
 * @return array Complete list of municipalities and their barangays
 */
function getAllNorthernSamarBarangays() {
    global $northern_samar_barangays;
    return $northern_samar_barangays;
}

/**
 * Function to count total barangays in Northern Samar
 * @return int Total number of barangays
 */
function countNorthernSamarBarangays() {
    global $northern_samar_barangays;
    $total = 0;
    foreach ($northern_samar_barangays as $barangays) {
        $total += count($barangays);
    }
    return $total;
}

/**
 * Function to search for a specific barangay across all municipalities
 * @param string $barangayName Name of the barangay to search
 * @return array List of municipalities where the barangay is found
 */
function searchNorthernSamarBarangay($barangayName) {
    global $northern_samar_barangays;
    $results = [];
    
    foreach ($northern_samar_barangays as $municipality => $barangays) {
        if (in_array($barangayName, $barangays)) {
            $results[] = $municipality;
        }
    }
    
    return $results;
}

