/**
 * Helper functions for Southern Leyte barangays data
 * Provides convenient ways to access and search barangay information
 */

/**
 * Get all municipalities/cities of Southern Leyte
 * @return array List of all municipalities and cities
 */
function get_southern_leyte_municipalities() {
    global $southern_leyte_barangays;
    return array_keys($southern_leyte_barangays);
}

/**
 * Get all barangays for a specific municipality
 * @param string $municipality Name of municipality
 * @return array List of barangays or empty array if not found
 */
function get_southern_leyte_barangays_by_municipality($municipality) {
    global $southern_leyte_barangays;
    return isset($southern_leyte_barangays[$municipality]) ? $southern_leyte_barangays[$municipality] : array();
}

/**
 * Get all barangays of Southern Leyte (flattened array)
 * @return array All barangays across all municipalities
 */
function get_all_southern_leyte_barangays() {
    global $southern_leyte_barangays;
    $all_barangays = array();
    foreach ($southern_leyte_barangays as $municipality => $barangays) {
        $all_barangays = array_merge($all_barangays, $barangays);
    }
    return $all_barangays;
}

/**
 * Count barangays in a municipality
 * @param string $municipality Name of municipality
 * @return int Number of barangays
 */
function count_southern_leyte_barangays($municipality) {
    global $southern_leyte_barangays;
    return isset($southern_leyte_barangays[$municipality]) ? count($southern_leyte_barangays[$municipality]) : 0;
}

/**
 * Get total number of barangays in Southern Leyte
 * @return int Total barangays count
 */
function get_total_southern_leyte_barangays() {
    global $southern_leyte_barangays;
    $total = 0;
    foreach ($southern_leyte_barangays as $barangays) {
        $total += count($barangays);
    }
    return $total;
}

/**
 * Search for a barangay by name
 * @param string $search_term Barangay name to search
 * @return array Array of municipalities where barangay was found
 */
function search_southern_leyte_barangay($search_term) {
    global $southern_leyte_barangays;
    $results = array();
    
    foreach ($southern_leyte_barangays as $municipality => $barangays) {
        if (in_array($search_term, $barangays)) {
            $results[] = $municipality;
        }
    }
    
    return $results;
}

/**
 * Get complete Southern Leyte barangays data
 * @return array Complete data structure
 */
function get_southern_leyte_barangays_data() {
    global $southern_leyte_barangays;
    return $southern_leyte_barangays;
}

